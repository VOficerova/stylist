//! Сайт-визитка Василисы Офицеровой.
//!
//! - [`content`] — всё, что написано на сайте: услуги, прайс, работы.
//! - [`view`] — шаблоны, которые превращают контент в HTML-страницу.
//! - [`qr`] — генератор QR-кода для карточки «Поделиться».
//! - `app` — поведение в браузере (собирается только в WebAssembly).
//!
//! Страница рендерится дважды одним и тем же кодом: бинарник `prerender` пишет готовый
//! `index.html` при сборке, а WASM-модуль оживляет его в браузере. Поэтому текст виден сразу,
//! до загрузки WASM, и доступен поисковикам.

pub mod content;
pub mod qr;
pub mod view;

#[cfg(target_arch = "wasm32")]
mod app;
